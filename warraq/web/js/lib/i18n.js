let lang = "en";
export function setLang(l) {
  lang = S[l] ? l : "en";
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}
export const getLang = () => lang;
export function t(key) {
  return (S[lang] && S[lang][key]) || S.en[key] || key;
}
